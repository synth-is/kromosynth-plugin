// synthis-et4.18: write the sampler spike's test instrument, a tiny SFZ and one short WAV, into <out dir>. The
// bytes are generated here (deterministically: integer maths on a fixed formula), not taken from any user's or the
// platform's instrument, and the WCLAP module carries them compiled in (webclap/emscripten/EmbedFiles.cmake).
// NOT part of the gate.
//
//   node scripts/webclap-sampler-data.mjs <out dir>
//
// tone.wav: 48 kHz, mono, 16-bit PCM, 1.0 s (96,044 bytes). A4 (440 Hz) with its 2nd and 3rd harmonics, a 5 ms
// linear fade-in and an exponential decay (time constant 0.4 s) to a 20 ms linear fade-out ending at exactly 0, so
// the waveform is distinctive enough to fit against and has no click at either end.
// test.sfz: one region over the whole keyboard, pitch_keycenter 69 (the tone's own pitch), one_shot (the sample plays
// to its end whatever the note-off does), amp_veltrack 0 (gain does not depend on velocity).
import fs from 'node:fs';
import path from 'node:path';

const out = process.argv[2];
if (!out) { console.error('usage: webclap-sampler-data.mjs <out dir>'); process.exit(2); }
fs.mkdirSync(out, { recursive: true });

const sr = 48000, n = sr, f0 = 440;
const pcm = new Int16Array(n);
for (let i = 0; i < n; ++i) {
	const t = i / sr;
	const tone = Math.sin(2 * Math.PI * f0 * t) + 0.5 * Math.sin(2 * Math.PI * 2 * f0 * t) + 0.25 * Math.sin(2 * Math.PI * 3 * f0 * t);
	const fadeIn = Math.min(1, t / 0.005);
	const fadeOut = Math.min(1, (n - 1 - i) / (0.02 * sr));
	pcm[i] = Math.round(0.45 * tone * fadeIn * fadeOut * Math.exp(-t / 0.4) * 32767);
}

const wav = Buffer.alloc(44 + n * 2);
wav.write('RIFF', 0); wav.writeUInt32LE(36 + n * 2, 4); wav.write('WAVE', 8);
wav.write('fmt ', 12); wav.writeUInt32LE(16, 16); wav.writeUInt16LE(1, 20); wav.writeUInt16LE(1, 22);
wav.writeUInt32LE(sr, 24); wav.writeUInt32LE(sr * 2, 28); wav.writeUInt16LE(2, 32); wav.writeUInt16LE(16, 34);
wav.write('data', 36); wav.writeUInt32LE(n * 2, 40);
for (let i = 0; i < n; ++i) wav.writeInt16LE(pcm[i], 44 + i * 2);
fs.writeFileSync(path.join(out, 'tone.wav'), wav);

fs.writeFileSync(path.join(out, 'test.sfz'),
`// Test instrument for the sampler WCLAP spike (synthis-et4.18), generated by scripts/webclap-sampler-data.mjs.
// Not a user instrument.
<region> sample=tone.wav pitch_keycenter=69 lokey=0 hikey=127 amp_veltrack=0 loop_mode=one_shot
`);
console.log(`wrote ${out}/tone.wav (${wav.length} bytes) and test.sfz`);
